logger = logging.getLogger("facelessforge.longform")

router = APIRouter(prefix="/api/longform", tags=["longform"])

STORAGE_DIR = Path(os.environ.get("STORAGE_DIR", "/opt/facelessforge/storage"))
STORAGE_DIR.mkdir(parents=True, exist_ok=True)
R2_BUCKET = os.environ.get("R2_BUCKET", "facelessforge-prod")
R2_PUBLIC = os.environ.get("R2_PUBLIC_BASE_URL", os.environ.get("STORAGE_PUBLIC_BASE_URL", "https://videos.ethinx.solutions"))

OPENROUTER_API_KEY = os.environ.get("OPENROUTER_API_KEY", "").strip()
TEASER_API_URL = os.environ.get("TEASER_API_URL", "http://host.docker.internal:8005").strip()
YOUTUBE_CLIENT_ID = os.environ.get("YOUTUBE_CLIENT_ID", "").strip()
YOUTUBE_CLIENT_SECRET = os.environ.get("YOUTUBE_CLIENT_SECRET", "").strip()
YOUTUBE_REFRESH_TOKEN = os.environ.get("YOUTUBE_REFRESH_TOKEN", "").strip()


def _now():
    return datetime.now(timezone.utc)


def _scrub(text: str, max_len: int = 80) -> str:
    if not text:
        return ""
    t = text.replace("\\", "\\\\").replace(":", "\\:").replace("'", "\\'").replace("\n", " ")
    return t[:max_len]


class LongformRequest(BaseModel):
    companyName: str = Field(..., min_length=1)
    industry: str = Field(default="Builder")
    channelId: Optional[str] = None
    plan: Optional[str] = None
    jobId: Optional[str] = None
    privacy: str = "public"  # public|private|unlisted
    duration_minutes: int = 10
    jobId: Optional[str] = None


class LongformResponse(BaseModel):
    jobId: str
    projectId: str
    script: Optional[str] = None
    videoPath: str
    publicUrl: str
    youtube: dict
    title: str
    description: str
    tags: List[str]
    status: str
    createdAt: str


