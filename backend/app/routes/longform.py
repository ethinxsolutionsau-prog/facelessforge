"""FacelessForge long-form YouTube uploader — 10 minute case study videos.

Pipeline:
  POST /api/longform/generate {companyName, industry, channelId, plan}
    -> OpenRouter: 10-min script with hooks (openrouter/free)
    -> B-roll from teaser-api _get_broll_clips() chain
    -> ffmpeg concat 10 clips * 60s = 600s, scale 1280x720, drawtext overlays
    -> upload to YouTube via google-api-python-client
    -> save project to Mongo

Auth: Uses get_current_user (JWT HS256, same secret as /api/auth/login).
Title/description/tags auto-generated by OpenRouter.
Thumbnail: optional Unsplash + drawtext (future).
"""
from __future__ import annotations

import logging
import os
import re
import subprocess
import time
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Optional, List

from fastapi import APIRouter, Depends, HTTPException, Request
